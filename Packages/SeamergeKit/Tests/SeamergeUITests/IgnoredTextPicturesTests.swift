import AppKit
import MergeModel
import Testing

@testable import SeamergeUI

/// Draws the page Ignored Text of Settings for the visual review, in every look, with a rule
/// selected and tried on a sample and with a long and an invalid pattern; and a comparison that
/// uses the rules.
@MainActor
@Suite(.serialized, .timeLimit(.minutes(1)))
struct IgnoredTextPicturesTests {
  @Test(arguments: Look.all)
  func ignoredTextIsPictured(look: Look) async throws {
    let settings = UserSettings.private()
    settings.enabledBuiltInIgnoreRules = [.timestamps]
    settings.customIgnoreRules = [
      IgnoreRule(name: "Build number", pattern: #"Build \d+"#),
      IgnoreRule(
        name: "Generated header",
        pattern: #"^// Generated by [A-Za-z]+ (version \d+(\.\d+)*)? on \w+ at .*$"#),
      IgnoreRule(name: "Broken", pattern: #"(\d+"#, isEnabled: false),
    ]
    try await picture(settings: settings, look: look, named: "ignored-text-\(look.name)")
  }

  @Test(arguments: [Look.light, .dark])
  func ignoredTextWithoutOwnRulesIsPictured(look: Look) async throws {
    try await picture(settings: .private(), look: look, named: "ignored-text-empty-\(look.name)")
  }

  /// A comparison of two logs whose times the rule for timestamps leaves out, with Show Ignored
  /// Changes on: the subtitle names the rules, and the times show as places of ignored changes.
  @Test(arguments: Look.all)
  func comparisonWithIgnoreRulesIsPictured(look: Look) async throws {
    let settings = UserSettings.private()
    settings.enabledBuiltInIgnoreRules = [.timestamps]
    let session = try await Session.diff(
      old: SourceFile(bytes: Data(IgnoreRulesWindowTests.old.utf8), label: "build.log"),
      new: SourceFile(bytes: Data(IgnoreRulesWindowTests.new.utf8), label: "build.log"),
      mode: .windowDefault, ignoring: settings.ignoreRules)
    try Windows.picture(
      session, context: SessionContext(), look: look,
      options: DisplayOptions(increasesContrast: look.increasesContrast), settings: settings,
      size: CGSize(width: 900, height: 360), named: "comparison-ignore-rules-\(look.name)"
    ) { controller in
      controller.perform(.toggleIgnoredChanges)
    }
  }

  @Test func generalPageIsPictured() throws {
    let controller = SettingsWindowController(
      settings: .private(), updates: UpdateSettingDouble(checksAutomatically: true),
      displayOptions: DisplayOptions())
    let window = try #require(controller.window)
    defer { window.close() }
    window.colorSpace = .sRGB
    window.appearance = Look.light.appearance
    try Rendering.write(Rendering.bitmap(of: window), named: "settings-general-light")
  }

  private func picture(settings: UserSettings, look: Look, named name: String) async throws {
    let controller = SettingsWindowController(
      settings: settings, updates: nil,
      displayOptions: DisplayOptions(increasesContrast: look.increasesContrast, reducesMotion: true)
    )
    let window = try #require(controller.window)
    defer { window.close() }
    window.colorSpace = .sRGB
    window.appearance = look.appearance
    controller.tabs.selectedTabViewItemIndex = 1
    let page = controller.ignoredText
    page.tableView.selectRowIndexes(IndexSet(integer: 0), byExtendingSelection: false)
    page.trialField.text = """
      2026-11-15 13:40:23.735+0100 Build 4711 started
      13:40:24 Compiling Session.swift
      Done.
      """
    await page.trialTask?.value
    window.contentView?.layoutSubtreeIfNeeded()
    try Rendering.write(Rendering.bitmap(of: window), named: name)
  }
}
